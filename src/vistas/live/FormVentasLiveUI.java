private void guardarRegistro(String estado) {
        String cliente = txtUsuarioStreaming.getText().trim();
        String productoStr = jComboBoxProductos.getSelectedItem().toString(); // <-- Aquí lee el ComboBox
        String cantidadStr = txtCantidad.getText().trim();

        if (cliente.isEmpty() || productoStr.equals("-- Seleccione un producto --") || cantidadStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor complete todos los campos y seleccione un producto.", "Campos requeridos", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // Ya no hacemos parseInt de productoStr porque ahora es texto (ej. "Polera Oversize")
            int cantidad = Integer.parseInt(cantidadStr);
            int idLiveActual = 13;
            
            

        Apartado nuevo = new Apartado();
        nuevo.setIdLive(idLiveActual);
        nuevo.setIdProducto(productoStr);
        nuevo.setNombreCliente(cliente);
        nuevo.setCantidad(cantidad);
        nuevo.setEstado(estado);
        String metodoPagoStr = jComboBoxMetodoPago.getSelectedItem().toString().trim();
        nuevo.setMetodoPago(metodoPagoStr);

        boolean exito = apartadoDAO.registrarApartado(nuevo);

        if (exito) {
            JOptionPane.showMessageDialog(this, "Registro guardado como " + estado);
            txtUsuarioStreaming.setText("");
           
            txtCantidad.setText("");
            
            cargarTabla(idLiveActual);
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos.", "Error", JOptionPane.ERROR_MESSAGE);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID de Producto y Cantidad deben ser números válidos.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
    }
}

    private String obtenerProductoMasVendido() {
    if (tblLive.getRowCount() == 0) {
        return "Ninguno (Sin ventas)";
    }

    java.util.Map<String, Integer> conteoProductos = new java.util.HashMap<>();

    // Recorrer la tabla para acumular cantidades de cada producto
    for (int i = 0; i < tblLive.getRowCount(); i++) {
        String estado = tblLive.getValueAt(i, 4).toString(); // Columna Estado
        
        if (estado.contains("VENDIDO")) {
            String producto = tblLive.getValueAt(i, 2).toString(); // Columna Producto
            int cantidad = Integer.parseInt(tblLive.getValueAt(i, 3).toString()); // Columna Cantidad

            conteoProductos.put(producto, conteoProductos.getOrDefault(producto, 0) + cantidad);
        }
    }

    if (conteoProductos.isEmpty()) {
        return "Ninguno con estado VENDIDO";
    }

    String masVendido = "";
    int maxCantidad = 0;

    for (java.util.Map.Entry<String, Integer> entry : conteoProductos.entrySet()) {
        if (entry.getValue() > maxCantidad) {
            maxCantidad = entry.getValue();
            masVendido = entry.getKey() + " (" + maxCantidad + " uds)";
        }
    }

    return masVendido;
}

   
      
