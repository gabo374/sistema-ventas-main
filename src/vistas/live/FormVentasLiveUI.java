    public final void cargarTabla(int idLive) {
    List<Apartado> lista = apartadoDAO.listarPorLive(idLive);
    modeloTabla.setRowCount(0); // Limpia la tabla

    int totalApartados = 0;
    int totalVendidos = 0;
    double ingresoTotal = 0.0;

    for (Apartado ap : lista) {
        double precioUnitario = ap.getPrecio();
        double monto = ap.getCantidad() * precioUnitario;
        String estado = ap.getEstado() != null ? ap.getEstado().toUpperCase() : "";

        // Si el estado es PENDIENTE o APARTADO lo suma a apartados
        if (estado.contains("PENDIENTE") || estado.contains("APARTADO")) {
            totalApartados += ap.getCantidad();
        } else if (estado.contains("VENDIDO") || estado.contains("VENTA")) {
            totalVendidos += ap.getCantidad();
            ingresoTotal += monto;
        }

        modeloTabla.addRow(new Object[]{
            ap.getIdApartado(),
            ap.getNombreCliente(),
            ap.getIdProducto(),
            ap.getCantidad(),
            ap.getEstado(),
            String.format("$%.2f", monto),            
            ap.getMetodoPago()
        });
    }

    IbITotalApartados.setText(String.valueOf(totalApartados));
    IbITotalVendidos.setText(String.valueOf(totalVendidos));
    IbIIngresoAcumulado.setText(String.format("$%.2f", ingresoTotal));
int stockInicial = 100; 
int stockDisponible = stockInicial - (totalApartados + totalVendidos);
    
IbITotalDisponibles.setText(String.valueOf(stockDisponible));
}

